/**
 * API Route: Custom Voices
 * GET /api/content-writer/custom-voices - List all custom voices
 */

import { NextRequest, NextResponse } from 'next/server';
import { createServerSupabaseClient } from '@/lib/supabase-server';

export async function GET(request: NextRequest) {
  try {
    const supabase = await createServerSupabaseClient();
    const {
      data: { user },
      error: authError,
    } = await supabase.auth.getUser();

    if (authError || !user) {
      return NextResponse.json(
        { error: 'Unauthorized' },
        { status: 401 }
      );
    }

    const { data: custom_voices, error } = await supabase
      .from('custom_voices')
      .select('*')
      .eq('user_id', user.id)
      .order('created_at', { ascending: false });

    if (error) {
      console.error('Error fetching custom voices:', error);
      return NextResponse.json(
        { error: 'Failed to fetch custom voices' },
        { status: 500 }
      );
    }

    return NextResponse.json({ custom_voices });
  } catch (error) {
    console.error('Error:', error);
    return NextResponse.json(
      { error: 'Internal server error' },
      { status: 500 }
    );
  }
}
